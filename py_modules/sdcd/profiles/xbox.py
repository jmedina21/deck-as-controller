def _axis(v: float) -> int:
    return max(0, min(0xFFFF, round(32768 + v * 32767)))


class XboxEncoder(Encoder):
    def encode(self, d: DeckInput | None, battery: Battery) -> bytes:
        r = bytearray(20)
        r[0] = 0x01
        if d is None:
            struct.pack_into("<4H", r, 1, 0x8000, 0x8000, 0x8000, 0x8000)
            return bytes(r)
        lx, ly = stick_unit(d.lx, d.ly)
        rx, ry = stick_unit(d.rx, d.ry)
        struct.pack_into("<4H", r, 1, _axis(lx), _axis(-ly), _axis(rx), _axis(-ry))  # +y down
        struct.pack_into("<2H", r, 9, d.lt >> 5, d.rt >> 5)  # 15 bit -> 10 bit
        hat = hat_direction(d)
        r[13] = 0 if hat is None else hat + 1
        r[14] = ((0x01 if d.a else 0) | (0x02 if d.b else 0) | (0x08 if d.x else 0)
                 | (0x10 if d.y else 0) | (0x40 if d.l1 else 0) | (0x80 if d.r1 else 0))
        r[15] = ((0x04 if d.view else 0) | (0x08 if d.menu else 0) | (0x10 if d.steam else 0)
                 | (0x20 if d.l3 else 0) | (0x40 if d.r3 else 0))
        r[17] = 0  # no controller profile active: paddles are reported, not remapped
        # Paddles: P1 upper right, P2 lower right, P3 upper left, P4 lower left
        r[19] = ((0x01 if d.r4 else 0) | (0x02 if d.r5 else 0)
                 | (0x04 if d.l4 else 0) | (0x08 if d.l5 else 0))
        return bytes(r)


class Xbox(Profile):
    id = "xbox_elite"
    label = "Xbox Elite (back buttons)"
    vendor_id = 0x045E
    product_id = 0x0B05
    version = 0x0503
    bt_name = "Xbox Elite Wireless Controller"
    service_name = "Xbox Wireless Controller"
    provider = "Microsoft"
    descriptor = DESCRIPTOR

    def new_encoder(self) -> Encoder:
        return XboxEncoder()

    def parse_rumble(self, msg: bytes) -> tuple[int, int, float | None] | None:
        # a2 03 <enable> <lt> <rt> <strong> <weak> <duration> <delay> <loop>
        # Magnitudes 0..100; duration in 10 ms units, played (loop + 1) times.
        # enable bits: 0x01 weak motor, 0x02 strong motor, 0x04/0x08 trigger motors
        if len(msg) < 10 or msg[0] != 0xA2 or msg[1] != 0x03:
            return None
        enable = msg[2]
        low = msg[5] if enable & 0x02 else 0
        high = msg[6] if enable & 0x01 else 0
        duration = msg[7] * 0.01 * (msg[9] + 1)
        return min(255, low * 255 // 100), min(255, high * 255 // 100), duration

    def side_reports(self, battery: Battery) -> list[bytes]:
        # Report 0x04: bits 0-1 level (0 empty .. 3 full), bits 2-3 power source
        # (0 = wired/charging, non-zero = battery), per SDL's Xbox Bluetooth driver.
        level = 3 if battery.percent > 70 else 2 if battery.percent > 40 else 1 if battery.percent > 10 else 0
        source = 0 if battery.charging else 0x04
        return [bytes([0x04, source | level])]
